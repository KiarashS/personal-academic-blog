import { writeFile } from 'node:fs/promises';
import * as simpleIcons from 'simple-icons';

/*
 * Writes `src/lib/profile-icons.ts`: one 24-unit glyph per service the profile
 * row can link to.
 *
 *   npm run icons
 *
 * Two kinds, and the file records which is which so the component knows how to
 * paint them.
 *
 * A service with a mark of its own gets that mark, taken from `simple-icons`
 * (CC0-1.0, a devDependency — only this script imports it, and only the paths
 * it needs are written out, so the package is not in the site's bundle). A
 * hand-drawn octocat would be both worse and wronger: these are the shapes
 * readers recognise without reading.
 *
 * The rest get a glyph in the house style — the same 24-unit stroked outline
 * the feed link and the heading anchors use. `linkedin` is here rather than
 * above because LinkedIn had its mark removed from simple-icons at its own
 * request, and drawing their trademark from memory is not the answer to that.
 */

// Every key `profileLinks` can produce. Ordered as the row renders.
const BRAND = {
  orcid: 'siOrcid',
  scholar: 'siGooglescholar',
  semanticScholar: 'siSemanticscholar',
  arxiv: 'siArxiv',
  github: 'siGithub',
  mastodon: 'siMastodon',
  bluesky: 'siBluesky',
};

/*
 * Drawn here rather than imported. Stroked, round caps and joins, on the same
 * 24-unit grid as `plugins/link-icon.ts`, so they sit at the weight of the
 * marks beside them at the size this row uses.
 */
const HOUSE = {
  // A sheet with a corner turned and two lines of writing on it.
  cv: 'M14 3H7a2 2 0 0 0-2 2v14a2 2 0 0 0 2 2h10a2 2 0 0 0 2-2V8zM14 3v5h5M9 13h6M9 17h4',
  // A card with an occupant and a line of title beside them: a profile, which
  // is what the service is, without borrowing the mark that names it.
  linkedin: 'M4 5h16v14H4zM10 15a2.5 2.5 0 0 1 4 0M12 10.5a1 1 0 1 1 0-.01',
  // A globe: the outline, the equator, and one meridian seen edge-on.
  website:
    'M12 3a9 9 0 1 0 0 18 9 9 0 0 0 0-18M3.5 9h17M3.5 15h17M12 3c2.4 2.4 3.6 5.4 3.6 9s-1.2 6.6-3.6 9c-2.4-2.4-3.6-5.4-3.6-9S9.6 5.4 12 3',
  // An envelope, flap down.
  email: 'M3 6h18v12H3zM3 7l9 6 9-6',
};

const brands = Object.entries(BRAND).map(([key, exported]) => {
  const icon = simpleIcons[exported];
  if (!icon) throw new Error(`simple-icons has no ${exported}; check the name or the version`);
  return [key, { path: icon.path, title: icon.title, kind: 'mark' }];
});

const house = Object.entries(HOUSE).map(([key, path]) => [key, { path, kind: 'line' }]);

const entries = [...brands, ...house].sort((a, b) => a[0].localeCompare(b[0]));

const body = entries
  .map(([key, icon]) => {
    const note = icon.title ? `  // ${icon.title}, from simple-icons (CC0-1.0).\n` : '';
    return `${note}  ${key}: { kind: '${icon.kind}', path: '${icon.path}' },`;
  })
  .join('\n');

const file = `import type { ProfileKey } from './types';

/*
 * Generated by \`scripts/build-profile-icons.mjs\` — run \`npm run icons\` after
 * changing it rather than editing this file.
 *
 * \`mark\` is a service's own logo, filled, taken from simple-icons (CC0-1.0).
 * \`line\` is a glyph of this site's own, stroked on the same 24-unit grid as
 * the rest of the icons here.
 */

export interface ProfileIcon {
  kind: 'mark' | 'line';
  path: string;
}

export const PROFILE_ICONS: Record<ProfileKey | 'cv' | 'email', ProfileIcon> = {
${body}
};
`;

const OUT = 'src/lib/profile-icons.ts';
await writeFile(OUT, file);
console.log(
  `wrote ${OUT}: ${brands.length} service marks, ${house.length} of the site's own, ` +
    `${file.length} bytes`,
);
