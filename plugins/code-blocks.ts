import type { Element, ElementContent, Root } from 'hast';

const NOT_CODE = new Set(['language-math', 'math-display', 'math-inline']);

function classesOf(node: Element): string[] {
  const classes = node.properties?.className;
  return Array.isArray(classes) ? classes.map(String) : [String(classes ?? '')];
}

function languageOf(code: Element): string | undefined {
  const match = classesOf(code).find((name) => name.startsWith('language-'));
  return match?.slice('language-'.length);
}

/**
 * Splits highlighted code into one array of nodes per line. A token can span a
 * newline — a block comment, a template string — so an element that does is
 * cloned into each line it covers rather than closed at the first break.
 */
function splitLines(nodes: ElementContent[]): ElementContent[][] {
  const lines: ElementContent[][] = [[]];
  const add = (node: ElementContent) => lines[lines.length - 1].push(node);

  for (const node of nodes) {
    if (node.type === 'text') {
      node.value.split('\n').forEach((part, index) => {
        if (index > 0) lines.push([]);
        if (part) add({ type: 'text', value: part });
      });
      continue;
    }

    if (node.type === 'element') {
      splitLines(node.children).forEach((children, index) => {
        if (index > 0) lines.push([]);
        if (children.length > 0) add({ ...node, children });
      });
      continue;
    }

    add(node);
  }

  return lines;
}

/** A line's text, for measuring what it starts with. */
function textOf(nodes: ElementContent[]): string {
  return nodes
    .map((node) =>
      node.type === 'text' ? node.value : node.type === 'element' ? textOf(node.children) : '',
    )
    .join('');
}

/** How far a line is indented, in characters; a tab counts as the four the stylesheet sets. */
function indentOf(nodes: ElementContent[]): number {
  const lead = /^[ \t]*/.exec(textOf(nodes))?.[0] ?? '';
  return [...lead].reduce((width, char) => width + (char === '\t' ? 4 : 1), 0);
}

/**
 * Wraps each line in a span the stylesheet can number, and returns how many
 * there are. The newline stays inside the span, so the block still breaks where
 * it did and `textContent` — what the copy button reads — is the source,
 * unchanged. The numbers themselves are generated by a CSS counter, which keeps
 * them out of the clipboard.
 */
function numberLines(code: Element, force = false): number {
  const lines = splitLines(code.children);
  // A file ending in a newline produces a last, empty line.
  if (lines.length > 1 && lines[lines.length - 1].length === 0) lines.pop();
  // A one-line block is not numbered, unless a line has to carry a mark.
  if (lines.length < 2 && !force) return 0;

  // The indent goes on the line as `--indent`, so a line that wraps can carry
  // on under its own first character rather than under the line number.
  code.children = lines.map((children, index) => {
    const indent = indentOf(children);
    return {
      type: 'element',
      tagName: 'span',
      properties: {
        className: ['code-line'],
        ...(indent > 0 ? { style: `--indent:${indent}` } : {}),
      },
      children:
        index === lines.length - 1 ? children : [...children, { type: 'text', value: '\n' }],
    };
  });

  return lines.length;
}

const label = (state: 'off' | 'on', word: string): Element => ({
  type: 'element',
  tagName: 'span',
  properties: { className: ['code-block__wrap-label', `code-block__wrap-label--${state}`] },
  children: [{ type: 'text', value: word }],
});

/**
 * The toggle that wraps long lines, written the way the copy button is: a
 * word, and the rest of its name for a screen reader. The word is what a
 * press will do, "wrap" or "unwrap". Both are here and the stylesheet shows
 * the one the reader's choice calls for (`data-code-wrap` on the root, set
 * before paint from what they chose last time), so the label is right on the
 * first frame, on every page, with no script having run. The hidden one is
 * `display: none` and not read out. With a label that says it, there is no
 * `aria-pressed`, which would announce the state twice.
 */
function wrapButton(): Element {
  return {
    type: 'element',
    tagName: 'button',
    properties: { type: 'button', className: ['code-block__wrap'] },
    children: [
      label('off', 'wrap'),
      label('on', 'unwrap'),
      {
        type: 'element',
        tagName: 'span',
        properties: { className: ['visually-hidden'] },
        children: [{ type: 'text', value: ' long lines' }],
      },
    ],
  };
}

/**
 * Wraps every `pre` in the chrome the reader sees — a bar carrying the language
 * and a copy button, above the code rather than over it — at build time, so a
 * prerendered page has them before any script runs. The button only needs a
 * click handler attached later.
 */
/** What `remarkCodeMeta` left on the `code` element, taken off it again. */
function takeMeta(code: Element | undefined): { mark: Set<number>; diff?: string; tab?: string } {
  const props = code?.properties ?? {};
  const mark = new Set(
    String(props.dataMark ?? '')
      .split(',')
      .map(Number)
      .filter((n) => n > 0),
  );
  const diff = typeof props.dataDiff === 'string' ? props.dataDiff : undefined;
  const tab = typeof props.dataTab === 'string' ? props.dataTab : undefined;
  delete props.dataMark;
  delete props.dataDiff;
  delete props.dataTab;
  return { mark, diff, tab };
}

/**
 * Marks the lines a fence asked for: `{2,4-6}` highlights, and a `diff-` fence
 * adds or removes. The marks are classes, and the plus and minus are drawn in
 * the number gutter by the stylesheet, so they are never copied: the copy
 * button gives the code as it is after the change.
 */
function markLines(code: Element, mark: Set<number>, diff: string | undefined): void {
  code.children.forEach((line, index) => {
    if (line.type !== 'element') return;
    const extra: string[] = [];
    if (mark.has(index + 1)) extra.push('code-line--mark');
    if (diff?.[index] === '+') extra.push('code-line--ins');
    if (diff?.[index] === '-') extra.push('code-line--del');
    if (extra.length === 0) return;
    const classes = line.properties?.className;
    line.properties = {
      ...line.properties,
      className: [...(Array.isArray(classes) ? classes.map(String) : []), ...extra],
    };
  });
}

export function rehypeCodeBlocks() {
  return (tree: Root) => {
    const walk = (node: Root | Element) => {
      const children = 'children' in node ? node.children : [];
      children.forEach((child, index) => {
        if (child.type !== 'element') return;
        if (child.tagName !== 'pre') {
          walk(child);
          return;
        }

        const code = child.children.find(
          (grandchild): grandchild is Element =>
            grandchild.type === 'element' && grandchild.tagName === 'code',
        );
        if (code && classesOf(code).some((name) => NOT_CODE.has(name))) return;
        const language = code ? languageOf(code) : undefined;
        const { mark, diff, tab } = takeMeta(code);
        const marked = mark.size > 0 || diff !== undefined;

        // The number gutter supplies the padding on a numbered block, so that
        // it can stay put while a long line scrolls under it.
        const lineCount = code ? numberLines(code, marked) : 0;
        if (code && marked) markLines(code, mark, diff);

        // How wide the gutter has to be, in digits. The stylesheet reserves
        // that much and right-aligns the number in it, so line 9 and line 10
        // start their code at the same column; a block that runs past 99 gets
        // a wider gutter rather than a step in the middle of it.
        const digits = String(lineCount).length;

        // A block that scrolls sideways has to be reachable by keyboard.
        const preClasses = [
          ...(lineCount > 0 ? ['numbered'] : []),
          ...(marked ? ['code-marked'] : []),
          ...(diff !== undefined ? ['code-diff'] : []),
        ];
        child.properties = {
          ...child.properties,
          tabIndex: 0,
          ...(preClasses.length > 0 ? { className: preClasses } : {}),
          ...(lineCount > 0 ? { style: `--code-digits:${digits}` } : {}),
        };

        const bar: Element[] = [];
        if (language) {
          bar.push({
            type: 'element',
            tagName: 'span',
            properties: { className: ['code-block__lang'], ariaHidden: 'true' },
            children: [{ type: 'text', value: diff === undefined ? language : `${language} diff` }],
          });
        }
        bar.push(wrapButton());
        bar.push({
          type: 'element',
          tagName: 'button',
          properties: { type: 'button', className: ['code-block__copy'] },
          children: [
            { type: 'text', value: 'copy' },
            {
              type: 'element',
              tagName: 'span',
              properties: { className: ['visually-hidden'] },
              children: [{ type: 'text', value: ' code to clipboard' }],
            },
          ],
        });

        children[index] = {
          type: 'element',
          tagName: 'div',
          // `dataTab` is read by `groupTabs` below and does not reach the page.
          properties: { className: ['code-block'], ...(tab ? { dataTab: tab } : {}) },
          children: [
            {
              type: 'element',
              tagName: 'div',
              properties: { className: ['code-block__bar'] },
              children: bar,
            },
            child,
          ],
        };
      });
    };
    walk(tree);
    groupTabs(tree);
  };
}

const isBlank = (node: ElementContent | Root['children'][number]): boolean =>
  node.type === 'text' && node.value.trim() === '';

/**
 * Consecutive fences that each name a tab become one block with a tab per
 * fence: the same code in Python and R, say, or a config for each platform.
 *
 * The tabs are radio buttons and labels, and which panel shows is decided by
 * the stylesheet from which one is checked, so the set works before any
 * script and without one. A radio group also gives the keyboard what a set of
 * tabs needs, arrow keys between them, with nothing to write. `PostBody` adds
 * one thing on top: picking Python in one set picks it in every set on the
 * page, and remembers it.
 *
 * A single fence with a tab, or a run broken by a paragraph, is left as an
 * ordinary block.
 */
const MAX_TABS = 12;

function groupTabs(tree: Root): void {
  let groups = 0;

  const tabOf = (node: ElementContent | Root['children'][number]): string | undefined =>
    node.type === 'element' && typeof node.properties?.dataTab === 'string'
      ? node.properties.dataTab
      : undefined;

  const walk = (parent: Root | Element) => {
    const children = parent.children as ElementContent[];
    for (let i = 0; i < children.length; i += 1) {
      const node = children[i];
      if (node.type !== 'element') continue;
      if (tabOf(node) === undefined) {
        walk(node);
        continue;
      }

      // The run: tabbed blocks with nothing but whitespace between them.
      const members: Element[] = [];
      let end = i;
      for (let j = i; j < children.length; j += 1) {
        const candidate = children[j];
        if (isBlank(candidate)) continue;
        if (candidate.type === 'element' && tabOf(candidate) !== undefined) {
          members.push(candidate);
          end = j;
          continue;
        }
        break;
      }

      for (const member of members) delete member.properties.dataTab;
      // The stylesheet has a rule per tab position, up to twelve; a longer run
      // is left as the separate blocks it was written as.
      if (members.length < 2 || members.length > MAX_TABS) continue;

      groups += 1;
      const name = `code-tabs-${groups}`;
      const tabs: ElementContent[] = [];
      const panels: Element[] = [];
      members.forEach((member, n) => {
        const id = `${name}-${n + 1}`;
        const label = tabLabels.get(member) ?? `Tab ${n + 1}`;
        // The radio sits inside its label, so when the arrow keys move to a
        // tab on a second row the browser scrolls that tab into view, not a
        // hidden input somewhere else. `data-text` reserves the bold width,
        // so choosing a tab does not shift the ones after it.
        tabs.push({
          type: 'element',
          tagName: 'label',
          properties: { htmlFor: [id], className: ['code-tabs__tab'], dataText: label },
          children: [
            {
              type: 'element',
              tagName: 'input',
              properties: {
                type: 'radio',
                name,
                id,
                className: ['code-tabs__input'],
                ...(n === 0 ? { checked: true } : {}),
              },
              children: [],
            },
            { type: 'text', value: label },
          ],
        });
        // Each fence's own bar goes: the set has one, with the tabs in it.
        panels.push({
          ...member,
          properties: {
            className: ['code-block', 'code-tabs__panel'],
            dataTabLabel: label,
          },
          children: member.children.filter(
            (child) =>
              !(
                child.type === 'element' &&
                Array.isArray(child.properties.className) &&
                child.properties.className.includes('code-block__bar')
              ),
          ),
        });
      });

      // The wrap and copy buttons, once for the set. Copy reads the code of
      // the tab that is showing (PostBody).
      const firstBar = members[0].children.find(
        (child): child is Element =>
          child.type === 'element' &&
          Array.isArray(child.properties.className) &&
          child.properties.className.includes('code-block__bar'),
      );
      const buttons = (firstBar?.children ?? []).filter(
        (child) => child.type === 'element' && child.tagName === 'button',
      );

      children.splice(i, end - i + 1, {
        type: 'element',
        tagName: 'div',
        properties: { className: ['code-tabs'] },
        children: [
          {
            type: 'element',
            tagName: 'div',
            properties: { className: ['code-block__bar', 'code-tabs__bar'] },
            children: [
              {
                type: 'element',
                tagName: 'div',
                properties: {
                  className: ['code-tabs__list'],
                  role: 'radiogroup',
                  ariaLabel: 'Version',
                },
                children: tabs,
              },
              ...buttons,
            ],
          },
          ...panels,
        ],
      });
    }
  };

  // The labels are read before the markers come off.
  const tabLabels = new Map<Element, string>();
  const collect = (parent: Root | Element) => {
    for (const node of parent.children as ElementContent[]) {
      if (node.type !== 'element') continue;
      const tab = tabOf(node);
      if (tab !== undefined) tabLabels.set(node, tab);
      else collect(node);
    }
  };
  collect(tree);
  walk(tree);
}
